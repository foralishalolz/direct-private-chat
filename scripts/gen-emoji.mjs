// Generates the bundled emoji table from emojibase-data.
// Run: node scripts/gen-emoji.mjs
import { writeFile } from "node:fs/promises";
import data from "emojibase-data/en/compact.json" with { type: "json" };

// Include the nested skin-tone variants along with each base emoji.
const GROUPS = ["smileys-emotion", "people-body", "animals-nature", "food-drink", "travel-places", "activities", "objects", "symbols", "flags"];
const rows = [];
for (const emoji of data) {
  if (typeof emoji.group !== "number") continue;
  // Unicode group 2 contains components; visible categories resume at 3.
  const group = emoji.group === 2 ? "people-body" : GROUPS[emoji.group < 2 ? emoji.group : emoji.group - 1];
  if (!group) continue;
  const tags = String(emoji.tags ?? "").split("|").filter(Boolean).slice(0, 3).join(" ");
  rows.push([emoji.unicode, group, emoji.label.toLowerCase() + (tags ? " " + tags : "")]);
  for (const skin of emoji.skins ?? []) rows.push([skin.unicode, group, skin.label.toLowerCase() + (tags ? " " + tags : "")]);
}
// Dedupe by glyph, keeping the first (canonical) entry.
const seen = new Set();
const unique = rows.filter(row => (seen.has(row[0]) ? false : (seen.add(row[0]), true)));
const out = {
  generated: new Date().toISOString().slice(0, 10),
  source: "emojibase-data en/compact.json",
  count: unique.length,
  groups: GROUPS,
  rows: unique,
};
await writeFile("lib/emoji-data.ts", "// Generated by scripts/gen-emoji.mjs — do not edit by hand.\nexport type EmojiRow = readonly [glyph: string, group: string, keywords: string];\nexport const EMOJI_GROUPS = " + JSON.stringify(GROUPS) + " as const;\nexport const EMOJI_ROWS: EmojiRow[] = " + JSON.stringify(unique) + " as EmojiRow[];\n");
console.log("emojis:", unique.length);
